export function L(key){
  const lang = (typeof localStorage!=='undefined' && localStorage.getItem('nutryx:lang')) || 'en';
  return (LANGS[lang] || LANGS.en)[key] ?? LANGS.en[key] ?? key;
}
export function isRTL(){ return ((LANGS[typeof localStorage!=='undefined'?localStorage.getItem('nutryx:lang')||'en':'en'])||LANGS.en).dir==='rtl'; }
export function getLangFlag(){ return ((LANGS[typeof localStorage!=='undefined'?localStorage.getItem('nutryx:lang')||'en':'en'])||LANGS.en).flag; }

export function setLang(lang){
  localStorage.setItem('nutryx:lang', lang);
  try{ window.dispatchEvent(new CustomEvent('nutryx:lang-changed', { detail: lang })); }catch(e){}
}

export function translateStatic(){
  try{
    document.querySelectorAll('[data-i18n]').forEach(el=>{
      const k=el.getAttribute('data-i18n'); if(k){ const v=L(k); if(v!==undefined) el.textContent=v; }
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el=>{
      const k=el.getAttribute('data-i18n-html'); if(k){ const v=L(k); if(v!==undefined) el.innerHTML=v; }
    });
    const ib=document.getElementById('install-btn');
    if(ib&&ib.getAttribute('data-i18n')){ const v=L(ib.getAttribute('data-i18n')); if(v!==undefined){ib.textContent=v;ib.setAttribute('aria-label',v);} }
    document.body.setAttribute('dir', isRTL()?'rtl':'ltr');
  }catch(e){ console.warn('translateStatic failed',e); }
}
